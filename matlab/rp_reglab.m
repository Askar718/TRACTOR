function s = rp_reglab(impl, a, v, feasET, feasD)
% RP_REGLAB  Обозначение режима: «К 0,08×3,6» (культиватор) или «Ф 0,12×2,7» (фреза).
% При заданных признаках выполнимости добавляется «*» (режим невыполним для дизельного
% аналога) или «**» (режим невыполним для электротрактора).
if impl == 1, m = 'К'; else, m = 'Ф'; end
s = [m ' ' rp_num(a, 2) '×' rp_num(v, 1)];
if nargin == 5
    if ~feasD, s = [s '*']; end
    if ~feasET, s = [s '**']; end
end
end
