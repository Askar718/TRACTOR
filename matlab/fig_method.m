function fig_method()
% Структурная схема методики сравнительной оценки: пять этапов и их содержание.
rp_init();
f = rp_fig(16.5, 14.4);
ax = rp_canvas(f);
S = {{'Этап 1', 'Исходные', 'данные'}, {'Этап 2', 'Обработка', 'опытов'}, ...
     {'Этап 3', 'Расчёт', 'показателей'}, {'Этап 4', 'Приведение', 'к единой шкале'}, ...
     {'Этап 5', 'Оценка', 'и вывод'}};
T = {
 {'Полевой опыт с ЭТ:', 'запись шины CAN,', 'журнал событий'}, ...
 {'Условия испытаний:', 'твёрдость и влажность', 'почвы, температура'}, ...
 {'Технические', 'характеристики ЭТ', 'и дизельного аналога'};
 {'Показатели', 'учётных проходов:', 'P, E, v, δ, W_0, e'}, ...
 {'Дисперсионный', 'и регрессионный анализ,', 'неопределённость'}, ...
 {'Модели агрегатов:', 'k(v), δ(φ), A(a, v),', 'тепловая модель'};
 {'Дизельный аналог:', 'буксование, мощность,', 'расход топлива'}, ...
 {'Модель смены:', 'развороты, переезды,', 'зарядка, автономность'}, ...
 {'Экономическая модель:', 'прямые и совокупные', 'затраты'};
 {'10 единичных', 'показателей', 'в 5 группах'}, ...
 {'Нормированные', 'разности d_i', 'в интервале [−1; 1]'}, ...
 {'Весовые коэффициенты:', 'метод анализа иерархий', 'и энтропийный метод'};
 {'Комплексный показатель', 'I = Σ w_i d_i,', 'проверка методом TOPSIS'}, ...
 {'Устойчивость вывода:', 'метод Монте-Карло,', 'вероятность P(I > 0)'}, ...
 {'Зоны оптимального', 'использования', 'электротрактора'}};
ws = 2.9; w = 3.95; h = 1.7; g = 0.3; x0 = 0.3;
xs = x0 + ws + 0.4 + (0:2) * (w + g);
ys = 12.4 - (0:4) * 2.5;
for r = 1:5
    rp_box(ax, x0, ys(r), ws, h, S{r}, [0.84 0.89 0.95], 9, 'bold');
    for c = 1:3
        rp_box(ax, xs(c), ys(r), w, h, T{r, c}, [0.97 0.97 0.97], 9);
    end
    plot(ax, [x0 + ws, xs(1)], [ys(r) + h/2, ys(r) + h/2], '-', 'Color', [0.55 0.55 0.55], 'LineWidth', 0.7);
    if r < 5
        rp_arrow(ax, x0 + ws/2, ys(r) - 0.03, x0 + ws/2, ys(r+1) + h + 0.05);
    end
end
text(8.25, 0.95, {'Результат: вывод о преимуществе ЭТ или дизельного аналога для заданного сочетания', ...
     '«операция – режим работы – организация работ – экономические условия»'}, 'Parent', ax, ...
     'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle', 'FontSize', 9.5);
rp_save(f, 'm_method');
end
