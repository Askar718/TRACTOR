function fig_tornado()
% Влияние параметров на комплексный показатель.
C = rp_init();
D = rp_read('src');
names = {'поправка к модели расхода топлива', 'коэффициент выбросов энергосистемы', 'КПД зарядного устройства', ...
         'КПД электропривода', 'годовая загрузка', 'коэффициент первичной энергии электроэнергии', 'ставка дисконтирования', ...
         'цена дизельного топлива', 'КПД батареи', 'КПД трансмиссии', 'цена электроэнергии', ...
         'доля затрат на ремонт и ТО ЭТ', 'коэффициент пересчёта цены FOB', 'отношение P_{ВОМ}/P_{е} дизеля', 'стоимость замены батареи'};
[~, o] = sort(abs(D.S2), 'descend');
f = rp_fig(16.5, 11.0);
ax = rp_ax(f, [8.1, 2.5, 8.1, 8.1]);
h = barh(ax, 1:15, [D.S1(o) D.S2(o)], 0.8, 'grouped');
set(h(1), 'FaceColor', C.et, 'EdgeColor', 'none'); set(h(2), 'FaceColor', C.d, 'EdgeColor', 'none');
plot(ax, [0 0], [0.4 15.6], '-', 'Color', [0.1 0.1 0.1], 'LineWidth', 0.8);
set(ax, 'YDir', 'reverse', 'YTick', 1:15, 'YTickLabel', names(o), 'YGrid', 'off', 'FontSize', 9.5);
ylim(ax, [0.4 15.6]); xlim(ax, [-0.3 0.3]);
xlabel(ax, 'Стандартизованный коэффициент регрессии');
rp_comma(ax, 'x', '%.1f');
rp_key(f, [4.0, 0.1, 10.0, 0.7], {{'сценарий 1', C.et, 'none', 'none', 'patch'}, {'сценарий 2', C.d, 'none', 'none', 'patch'}}, 2);
rp_save(f, 'm_tornado');
end
