function fig_hierarchy()
% Иерархия показателей сравнительной оценки.
rp_init();
W = rp_read('weights');
f = rp_fig(16.5, 12.4);
ax = rp_canvas(f);
G = {'Энергетические', 'Технологические', 'Экономические', 'Экологические', 'Автономность'};
cnt = [2 3 2 2 1];
idx = [0 cumsum(cnt)];
gw = zeros(1, 5);
for g = 1:5, gw(g) = sum(W.w_ahp(idx(g)+1:idx(g+1))); end
N = {'I_1 – удельные затраты подведённой энергии, МДж/га', ...
     'I_2 – удельные затраты первичной энергии, МДж/га', ...
     'I_3 – коэффициент выполнения сменного задания', ...
     'I_4 – буксование движителей, %', ...
     'I_5 – запас мощности, %', ...
     'I_6 – удельные прямые эксплуатационные затраты, тг/га', ...
     'I_7 – удельные совокупные затраты, тг/га', ...
     'I_8 – выбросы CO_2 с учётом производства энергии, кг/га', ...
     'I_9 – выбросы CO_2 в месте выполнения работ, кг/га', ...
     'I_{10} – доля сменного задания без восполнения энергии'};
rowh = 1.08; top = 11.9;
xg = 3.3; wg = 3.3; xi = 7.4; wi = 9.0;
ygm = zeros(1, 5);
k = 0;
for g = 1:5
    yt = top - k * rowh;
    hb = cnt(g) * rowh;
    ygm(g) = yt - hb/2;
    rp_box(ax, xg, yt - hb + 0.08, wg, hb - 0.16, {G{g}, ['w = ' rp_num(gw(g), 3)]}, [0.90 0.90 0.90], 9.5);
    for j = 1:cnt(g)
        k = k + 1;
        yi = yt - j * rowh;
        rp_box(ax, xi, yi + 0.1, wi, rowh - 0.2, N{k}, [0.99 0.99 0.99], 9);
        rp_arrow(ax, xg + wg, ygm(g), xi - 0.02, yi + rowh/2);
    end
end
rp_box(ax, 0.1, ygm(3) - 1.6, 2.7, 3.2, {'Цель:', 'сравнительная', 'оценка ЭТ и', 'дизельного', 'аналога'}, [0.80 0.88 0.97], 9.5, 'bold');
for g = 1:5
    rp_arrow(ax, 2.8, ygm(3), xg - 0.02, ygm(g));
end
rp_save(f, 'm_hierarchy');
end
