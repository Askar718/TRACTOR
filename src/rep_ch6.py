def _zo(D, impl, l):
    return D.zo[(D.zo.implement == impl) & np.isclose(D.zo.l_km, l)].sort_values("S_task")


def s_cap(D, impl, l):
    """Наибольшее сменное задание, выполнимое электротрактором за смену, га."""
    return _zo(D, impl, l).S_shift_ET.max()


def one_charge(D, impl, l):
    """Площадь, обрабатываемая без подзарядки с учётом энергии на переезды, га."""
    return _zo(D, impl, l).A_one.mean()


def org_threshold(D, impl, l):
    """Граничное сменное задание: электротрактор выполняет задание и I > 0, га (0 – не предпочтителен)."""
    g = _zo(D, impl, l)
    neg = g[g.I < 0]
    thr = neg.S_task.min() if len(neg) else np.inf
    if len(neg) and thr <= g.S_task.min() + 1e-9:
        return 0.0
    return min(thr, s_cap(D, impl, l))


def econ_threshold(D, impl, Ty):
    """Наименьшая цена дизельного топлива (тг/л), при которой совокупные затраты ЭТ ниже."""
    g = D.ze[(D.ze.implement == impl) & np.isclose(D.ze.T_year, Ty)].sort_values("c_D")
    pos = g[g.dC_tot < 0]
    return pos.c_D.min() if len(pos) else np.nan


def bound(D, impl, v, col):
    """Наибольшая глубина (см), при которой запас col ≥ 0 на скорости v (линейная интерполяция).

    Возвращает (глубина, признак достижения верхней границы расчётной сетки)."""
    g = D.zt[D.zt.implement == impl]
    vv = g.v.unique()[np.argmin(abs(g.v.unique() - v))]
    gg = g[np.isclose(g.v, vv)].sort_values("a")
    a, m = gg.a.values, gg[col].values
    ok = np.where(m >= 0)[0]
    if len(ok) == 0:
        return np.nan, False
    i = ok[-1]
    if i == len(a) - 1:
        return 100 * a[i], True
    return 100 * (a[i] + (a[i + 1] - a[i]) * m[i] / (m[i] - m[i + 1])), False


def ab(D, impl, v, col):
    x, edge = bound(D, impl, v, col)
    return ("не менее " if edge else "") + f(x, 1)


def v_cross(D):
    """Скорость, выше которой допустимая глубина культивации для Д больше, чем для ЭТ."""
    g = D.zt[D.zt.implement == "культиватор"]
    for v in np.sort(g.v.unique()):
        if bound(D, "культиватор", v, "mrg_ET")[0] < bound(D, "культиватор", v, "mrg_D")[0]:
            return v
    return np.nan


