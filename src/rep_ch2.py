def plan_table(D):
    w = D.passes[(D.passes.kind == "рабочий")]
    rows = []
    for impl in ("культиватор", "фреза"):
        g = w[w.implement == impl]
        for (a, v), gg in g.groupby(["a_plan_m", "v_plan_kmh"]):
            gear = gg.gear.iloc[0]
            lim = gg[gg.limit_attempt]
            if len(lim):
                rows.append((impl, f(a, 2), f(v, 1), gear, "–", "–", "–",
                             f"проход {int(lim.pass_no.iloc[0])} прерван"))
                continue
            nums = []
            for b in (1, 2, 3):
                x = gg[gg.block == b]
                nums.append(", ".join(str(int(n)) for n in x.pass_no) if len(x) else "–")
            rows.append((impl, f(a, 2), f(v, 1), gear, *nums, ""))
    return rows


