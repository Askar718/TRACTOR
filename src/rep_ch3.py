"""Раздел 3. Результаты полевых испытаний электротрактора."""
import numpy as np
import pandas as pd

from repdata import FIG, ROOT, f, pc, rng


def fs(x, d=1):
    return f(x, d) if np.isfinite(x) else "–"


def build(doc, D):
    P, M = D.P, D.M
    doc.h1(3, "Результаты полевых испытаний электротрактора")

    # ------------------------------------------------------------------ 3.1
    doc.h2("3.1", "Структура рабочего цикла и баланс энергии")
    s = {k: D.ses_row(k) for k in ("C", "T1", "T2")}
    doc.p("Запись серии опытов с культиватором приведена на рисунке 3.1. Потребляемая мощность изменяется циклически: "
          "учётные проходы (8–16 кВт) чередуются с разворотами (около 3 кВт) и стоянками для измерения показателей "
          "качества работы (0,18 кВт). Степень заряженности батареи снижается пропорционально отданной энергии и за серию "
          f"уменьшилась с {f(s['C'].soc_start, 0)} до {f(s['C'].soc_end, 0)} %.")
    doc.fig(FIG / "m_session.png", "Мощность, потребляемая от батареи, и степень заряженности батареи в серии опытов с культиватором (15.09.2026)")
    b = D.bal
    tot = b.groupby("session")[["t_s", "E_kWh"]].sum()

    def share(sess, st, col="E_kWh"):
        return b[(b.session == sess) & (b.stype == st)][col].sum() / tot.loc[sess, col]
    S3 = ("C", "T1", "T2")
    doc.p(f"На рабочие проходы приходится {rng([share(k, 'рабочий ход') for k in S3], 0, 100)} % энергии при "
          f"{rng([share(k, 'рабочий ход', 't_s') for k in S3], 0, 100)} % времени серии (рисунок 3.2, "
          "таблица 3.1). Большая доля времени стоянок для измерений обусловлена программой испытаний и в производственных "
          "условиях отсутствует; энергия, затрачиваемая на этих стоянках, пренебрежимо мала. На развороты и переезды "
          f"приходится {rng([share(k, 'разворот') + share(k, 'переезд') for k in S3], 0, 100)} % "
          "энергии; эти данные использованы в модели смены (подраздел 4.3).")
    doc.fig(FIG / "m_balance.png", "Распределение энергии (а) и времени (б) по видам работ в сериях опытов")
    order = ["рабочий ход", "разворот", "переезд", "гидропривод", "ВОМ", "замеры", "стоянка"]
    names = {"рабочий ход": "Рабочие проходы", "разворот": "Развороты", "переезд": "Переезды", "гидропривод": "Работа гидросистемы (подъём и опускание машины)",
             "ВОМ": "Вращение ротора без нагрузки", "замеры": "Стоянки для измерений", "стоянка": "Стоянка в режиме готовности"}
    rows = []
    for st in order:
        r = [names[st]]
        for k in ("C", "T1", "T2"):
            x = b[(b.session == k) & (b.stype == st)]
            r += [f(x.t_s.sum() / 60, 1) if len(x) else "–", f(x.E_kWh.sum(), 3) if len(x) else "–"]
        rows.append(r)
    rows.append(["Итого"] + sum([[f(tot.loc[k, 't_s'] / 60, 1), f(tot.loc[k, 'E_kWh'], 3)] for k in ("C", "T1", "T2")], []))
    doc.table("Баланс времени и энергии по видам работ",
              [["Вид работ", ("Культиватор, 15.09", 2), ("Фреза, 14.10", 2), ("Фреза, 15.10", 2)],
               ["", "t, мин", "E, кВт·ч", "t, мин", "E, кВт·ч", "t, мин", "E, кВт·ч"]],
              rows, widths=[4.0, 2.1, 2.1, 2.1, 2.1, 2.0, 2.1], size=11, align=["left"] + ["center"] * 6)
    bg = D.bg
    doc.p(f"Мощность во вспомогательных режимах приведена в таблице 3.2. В режиме готовности трактор потребляет "
          f"{f(D.bgv('стоянка'), 2)} кВт: питание контроллеров, системы управления батареей, преобразователя бортовой сети и "
          "вращение насоса гидросистемы без нагрузки (около 480 мин^{-1}). Работа гидросистемы при подъёме и опускании машины требует "
          f"{f(D.bgv('работа гидро'), 2)} кВт, вращение ротора фрезы без нагрузки – {f(D.bgv('холостое'), 2)} кВт, разворот на "
          f"поворотной полосе – {f(D.bgv('разворот'), 2)} кВт при средней продолжительности {f(D.S['turn']['t_s'], 1)} с, "
          f"транспортный переезд со скоростью 15,4 км/ч – {f(D.bgv('транспорт'), 2)} кВт. Мощность в таблице 3.2 определена "
          "по установившимся участкам соответствующих режимов без переходных процессов включения и выключения, поэтому "
          "продолжительность наблюдений и средние значения отличаются от данных таблицы 3.1, где учтено всё время работы "
          "в каждом режиме.")
    rn = {"стоянка": "Стоянка в режиме готовности", "работа гидро": "Работа гидронавесной системы",
          "холостое": "Вращение ротора фрезы без нагрузки (ВОМ 540)", "транспорт": "Транспортный переезд (передача H)",
          "разворот": "Разворот на поворотной полосе"}
    rows = []
    for k, n in rn.items():
        g = bg[bg.regime.str.startswith(k)]
        rows.append((n, f(g.t_s.sum() / 60, 1), f(g.P_mean_kW.mean(), 2), f(g.P_sd_kW.mean(), 2)))
    doc.table("Мощность во вспомогательных режимах",
              ["Режим", "Продолжительность наблюдений, мин", "Средняя мощность P̄, кВт", "Среднее квадратическое отклонение s_{P}, кВт"],
              rows, widths=[6.5, 3.3, 3.2, 3.5], size=11, align=["left", "center", "center", "center"])

    # ------------------------------------------------------------------ 3.2
    doc.h2("3.2", "Энергетические показатели на учётных проходах")
    doc.p("Характерные записи учётных проходов приведены на рисунках 3.3 и 3.4. На разгонном участке мощность "
          "нарастает в течение 8–12 с, после чего на учётной делянке устанавливается режим с коэффициентом вариации "
          f"мощности около {pc(M['cv_P'], 1)} % (медиана по всем проходам). Это подтверждает достаточность разгонного "
          "участка длиной 20 м и правомерность использования средних значений по учётной делянке. Частота вращения "
          "тягового электродвигателя при работе с культиватором и частота вращения ВОМ при работе с фрезой на учётной делянке "
          "практически постоянны; кратковременные снижения частоты вращения ВОМ на тяжёлых режимах рассмотрены в подразделе 3.6.")
    doc.fig(FIG / "m_pass_cult.png", "Запись прохода 4 с культиватором (a = 0,11 м, v = 4,5 км/ч): мощность, ток и частота вращения тягового электродвигателя")
    doc.fig(FIG / "m_pass_till.png", "Запись прохода 1 с фрезой (a = 0,12 м, v = 2,7 км/ч): мощность, ток тягового электродвигателя и частота вращения ВОМ")
    r = D.reg
    rows = []
    for x in r.itertuples():
        rows.append((x.implement, f(x.a_plan, 2), f(x.v_plan, 1), x.gear, f"{f(x.P_mean, 2)} ± {f(x.P_ci, 2)}",
                     f(x.v_mean, 2), fs(x.slip_mean * 100, 1), f(x.W_mean, 3), f"{f(x.e_mean, 1)} ± {f(x.e_ci, 1)}", f(x.eV_mean, 1)))
    doc.p("Показатели учётных проходов, осреднённые по трём повторностям, приведены в таблице 3.3 (значения по "
          "отдельным проходам – в приложении Б).")
    doc.table("Показатели агрегатов на учётных проходах (среднее ± полуширина доверительного интервала при P = 0,95)",
              ["Машина", "a, м", "v_{зад}, км/ч", "Пере-\nдача", "P̄, кВт", "v, км/ч", "δ, %", "W_{0}, га/ч", "e, кВт·ч/га", "e_{V}, кДж/м³"],
              rows, widths=[2.3, 1.2, 1.4, 1.3, 2.4, 1.4, 1.2, 1.6, 2.5, 1.7], size=10)
    doc.p("Прочерк в графе «δ» означает, что на данной передаче холостые проходы не выполнялись (подраздел 2.6).")
    rc, rt = r[r.implement == "культиватор"], r[r.implement == "фреза"]
    doc.p(f"Мощность, потребляемая агрегатом с культиватором, изменяется от {f(rc.P_mean.min(), 1)} до {f(rc.P_mean.max(), 1)} кВт, "
          f"агрегатом с фрезой – от {f(rt.P_mean.min(), 1)} до {f(rt.P_mean.max(), 1)} кВт (рисунок 3.5). Мощность агрегата с "
          "культиватором растёт со скоростью быстрее, чем по линейному закону, что согласуется с квадратичной "
          "зависимостью удельного тягового сопротивления от скорости. Мощность агрегата с фрезой возрастает линейно с "
          "увеличением объёма почвы, обрабатываемой в единицу времени.")
    doc.fig(FIG / "m_power_v.png", "Мощность, потребляемая от батареи, в зависимости от скорости: а) культиватор; б) фреза. Точки – опыт (среднее и доверительный интервал), линии – расчёт по модели (подраздел 3.10)")
    doc.p(f"Расход энергии на 1 га (рисунок 3.6) определяется главным образом глубиной обработки. "
          f"Для культиватора увеличение глубины с 0,08 до 0,14 м повышает расход энергии с "
          f"{f(rc[rc.a_plan == 0.08].e_mean.mean(), 1)} до {f(rc[rc.a_plan == 0.14].e_mean.mean(), 1)} кВт·ч/га, т. е. в "
          f"{f(rc[rc.a_plan == 0.14].e_mean.mean() / rc[rc.a_plan == 0.08].e_mean.mean(), 2)} раза при увеличении глубины в "
          "1,75 раза; влияние скорости невелико. Расход энергии на 1 га при фрезеровании в "
          f"{f(rt.e_mean.mean() / rc.e_mean.mean(), 1)} раза выше, чем при культивации, и, в отличие от культивации, "
          "снижается с ростом скорости: при постоянной частоте вращения ротора увеличение подачи на нож уменьшает "
          "затраты энергии на повторное крошение почвы, а затраты на вращение ротора распределяются на большую площадь.")
    doc.fig(FIG / "m_energy_ha.png", "Расход энергии батареи на 1 га в зависимости от глубины обработки: а) культиватор; б) фреза. Точки – среднее по трём повторностям, отрезки – доверительный интервал при P = 0,95")

    # ------------------------------------------------------------------ 3.3
    doc.h2("3.3", "Результаты дисперсионного анализа")
    rows = []
    for key, name in (("cult_e_kWh_ha", "Культиватор"), ("till_e_kWh_ha", "Фреза")):
        t = D.anova[key]
        for x in t.itertuples():
            src = {"Блоки": "Повторности (блоки)", "Итого": "Общая"}.get(x.source, x.source)
            rows.append((name if x.Index == 0 else "", src, int(x.df), f(x.SS, 3), f(x.MS, 3) if np.isfinite(x.MS) else "–",
                         f(x.F, 2) if np.isfinite(x.F) else "–",
                         ("< 0,001" if x.p < 0.001 else f(x.p, 3)) if np.isfinite(x.p) else "–", f(x.eta2, 3),
                         f(x.eta2_adj, 3) if np.isfinite(x.eta2_adj) else "–"))
    doc.p("Результаты дисперсионного анализа расхода энергии на 1 га приведены в таблице 3.4.")
    doc.table("Дисперсионный анализ расхода энергии батареи на 1 га",
              ["Машина", "Источник изменчивости", "Число степеней свободы", "Сумма квадратов", "Средний квадрат", "F", "p", "η² (тип I)", "η² (тип II)"],
              rows, widths=[2.0, 3.3, 1.6, 1.9, 1.8, 1.6, 1.5, 1.4, 1.4], size=10, align=["left", "left"] + ["center"] * 7)
    ce, te = D.anova["cult_e_kWh_ha"], D.anova["till_e_kWh_ha"]
    cp, tp = D.anova["cult_power_kW"], D.anova["till_power_kW"]
    doc.p(f"На долю глубины обработки приходится {pc(ce.eta2[1], 1)} % общей суммы квадратов расхода энергии на 1 га при "
          f"культивации и {pc(te.eta2[1], 1)} % при фрезеровании (p < 0,001); по суммам квадратов, скорректированным на "
          f"скорость, – {pc(ce.eta2_adj[1], 1)} и {pc(te.eta2_adj[1], 1)} %, т. е. вывод о преобладающем влиянии глубины не "
          "зависит от порядка включения факторов. Влияние скорости значимо в обоих случаях, но при культивации "
          f"мало (η² = {f(ce.eta2[2], 4)}, p = {f(ce.p[2], 3)}), а при фрезеровании существенно (η² = {f(te.eta2[2], 3)}). "
          f"Взаимодействие глубины и скорости значимо при фрезеровании (p = {f(te.p[3], 4)}) и незначимо при культивации "
          f"(p = {f(ce.p[3], 2)}). Эффект блоков незначим (p = {f(ce.p[0], 2)} и {f(te.p[0], 2)}): результаты, полученные в "
          "трёх полосах участка, а для фрезы – и в разные дни при различной температуре воздуха, систематически не "
          "различаются.")
    doc.p(f"Для мощности P влияние глубины и скорости соизмеримо (η² = {f(cp.eta2[1], 2)} и {f(cp.eta2[2], 2)} для культиватора, "
          f"{f(tp.eta2[1], 2)} и {f(tp.eta2[2], 2)} для фрезы), а взаимодействие значимо для обеих машин (p < 0,001), "
          "поскольку основное слагаемое мощности пропорционально произведению глубины и скорости (дисперсионный анализ "
          "мощности выполнен по той же модели; таблицы приведены в электронных материалах, приложение Е). Остаточное среднее квадратическое "
          f"отклонение мощности составляет {f(np.sqrt(cp.MS[4]), 2)} кВт для культиватора и {f(np.sqrt(tp.MS[4]), 2)} кВт для фрезы.")

    # ------------------------------------------------------------------ 3.4
    doc.h2("3.4", "Тяговые свойства и буксование")
    doc.p("Тяговое сопротивление культиватора определялось косвенно, без динамометрирования, по балансу мощности "
          "тягового электропривода. Касательная сила тяги движителей")
    doc.eq(r"F_\text{к} = \frac{1000\,\eta_\text{эп}\,\eta_\text{тр}\,(\bar P - P_\text{всп})\,(1 - \delta)}{v_\text{м}},")
    doc.where([("F_{к}", "касательная сила тяги, Н"),
               ("η_{эп}", f"КПД тягового электропривода «преобразователь частоты – асинхронный двигатель» (принят {f(P['eta_ep'], 2)})"),
               ("η_{тр}", f"КПД механической трансмиссии (принят {f(P['eta_tr'], 2)})"),
               ("P_{всп}", f"мощность, потребляемая системами трактора в режиме готовности, {f(P['P_aux'], 2)} кВт"),
               ("v_{м}", "фактическая скорость, м/с")])
    doc.p("При холостом проходе (δ = 0, тяговое сопротивление отсутствует) касательная сила тяги равна силе "
          "сопротивления передвижению трактора F_{f}. По холостым проходам определён коэффициент сопротивления "
          f"передвижению f = F_{{f}}/G = {f(M['f_roll'], 3)}, где G = m·g – вес трактора, Н. Тяговое сопротивление "
          "культиватора и его удельное значение на единицу площади поперечного сечения обрабатываемого слоя")
    doc.eq(r"R = F_\text{к} - f\,m\,g, \qquad k = \frac{R}{B\,a}.")
    doc.p("Абсолютные значения F_{к}, R и k зависят от принятых КПД: изменение произведения η_{эп}·η_{тр} в пределах "
          "0,71–0,84 (таблица 4.1) изменяет их на −9…+8 %. При расчёте показателей дизельного аналога эти КПД используются "
          "и при обратном переходе от сопротивления к мощности (подраздел 4.2), поэтому их влияние на результат сравнения "
          "в значительной мере компенсируется; остаточное влияние оценено в анализе чувствительности (подраздел 5.6).")
    rg = D.S["regressions"]["cult_k"]
    doc.p("Зависимость удельного сопротивления от скорости аппроксимирована упрощённой формулой В. П. Горячкина "
          "[@goryachkin1965,sineokov1977] (здесь и далее после знака «±» указана стандартная ошибка коэффициента регрессии):")
    doc.eq(r"k = k_0 + \varepsilon\,v_\text{м}^2,")
    doc.where([("k_{0}", f"составляющая, не зависящая от скорости: {f(M['k0'] / 1e3, 2)} ± {f(rg['bse']['Intercept'], 2)} кН/м²"),
               ("ε", f"коэффициент скоростной составляющей: {f(M['eps'] / 1e3, 2)} ± {f(rg['bse']['v2'], 2)} кН·с²/м⁴")])
    doc.p(f"Оба коэффициента значимы (p < 0,001); коэффициент детерминации R² = {f(rg['R2'], 2)}, остаточное среднее "
          f"квадратическое отклонение {f(rg['s'], 2)} кН/м² (рисунок 3.7, а). Невысокое значение R² объясняется тем, что "
          f"разброс k между проходами ({f(D.cult.k_Nm2.min() / 1e3, 1)}–{f(D.cult.k_Nm2.max() / 1e3, 1)} кН/м²) соизмерим с "
          "влиянием скорости в исследованном диапазоне; при этом расчётная мощность агрегата отличается от измеренной в среднем "
          f"на {f(D.S['validation_mape'], 1)} % (подраздел 3.10). Удельное сопротивление {f(D.cult.k_Nm2.min() / 1e4, 1)}–{f(D.cult.k_Nm2.max() / 1e4, 1)} Н/см² соответствует плотной почве "
          f"твёрдостью 1,47 МПа. Тяговое сопротивление культиватора составило {f(D.cult.R_N.min() / 1e3, 2)}–"
          f"{f(D.cult.R_N.max() / 1e3, 2)} кН; наибольшее значение находится в пределах диапазона номинального тягового усилия "
          "тракторов класса 0,6 (5,4–8,1 кН) [@gost27021].")
    doc.p("Зависимость буксования от коэффициента использования сцепного веса φ = R/G (кривая буксования) "
          "аппроксимирована выражением [@guskov1988,kutkov2004]")
    doc.eq(r"\varphi = \varphi_{\max}\left[1 - e^{-k_\delta \delta}\right] \;\Leftrightarrow\; \delta = -\frac{1}{k_\delta}\ln\!\left(1 - \frac{\varphi}{\varphi_{\max}}\right),")
    doc.where([("φ_{max}", f"предельное значение коэффициента использования сцепного веса: {f(M['phi_max'], 3)}"),
               ("k_{δ}", f"параметр кривой буксования: {f(M['k_slip'], 2)}")])
    rc = D.reg[D.reg.implement == "культиватор"]
