def short(impl, a, v, x=None):
    s = f"{'К' if impl == 'культиватор' else 'Ф'} {f(a, 2)}×{f(v, 1)}"
    if x is not None:
        if not x.feas_D:
            s += "*"
        if not x.feas_ET:
            s += "**"
    return s


def verdict(p):
    if p >= 0.9:
        return "устойчивое ЭТ"
    if p >= 0.5:
        return "условное ЭТ"
    if p > 0.1:
        return "условное Д"
    return "устойчивое Д"


def rng(s, d=0, k=1.0):
    """Диапазон «мин–макс» ряда s (с множителем k) в формате отчёта."""
    lo, hi = k * float(np.nanmin(s)), k * float(np.nanmax(s))
    return f"{f(lo, d)}–{f(hi, d)}" if f(lo, d) != f(hi, d) else f(lo, d)


