def short(impl, a, v, x=None):
    s = f"{'К' if impl == 'культиватор' else 'Ф'} {f(a, 2)}×{f(v, 1)}"
    if x is not None:
        if not x.feas_D:
            s += "*"
        if not x.feas_ET:
            s += "**"
    return s


def verdict(p):
    if p >= 0.9:
        return "устойчивое ЭТ"
    if p >= 0.5:
        return "условное ЭТ"
    if p > 0.1:
        return "условное Д"
    return "устойчивое Д"


def pp_word(lo, hi):
    """Согласование слова «процентный пункт» с границами диапазона."""
    return "процентного пункта" if (abs(hi - round(hi)) > 1e-9 or abs(lo - round(lo)) > 1e-9) else "процентных пунктов"


