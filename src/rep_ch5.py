        ("Курс доллара США, тг", f(P['usd_kzt'], 2), "НБРК, 18.10.2026 [@nbk]"),
        ("Цена ЭТ YL254ET у дилера, тыс. тг", f(price_ET / 1e3, 0), f"{f(P['price_ET_usd'], 0)} $ × курс × {f(P['k_landed'], 3)} [@jinma_price]"),
        ("Цена Д JM-254 у дилера, тыс. тг", f(price_D / 1e3, 0), f"{f(P['price_D_usd'], 0)} $ × курс × {f(P['k_landed'], 3)} [@jm254_price]"),
        ("Цена электроэнергии, тг/(кВт·ч)", f(P['c_el'], 2), "предельная цена ЭнергоСбыт АЖК с 12.09.2026, с НДС [@esalmaty]"),
        ("Цена дизельного топлива, тг/л", f(P['c_D'], 0), "средняя розничная, сентябрь – октябрь 2026 г. [@inform_fuel,zakon_fuel]"),
        ("Стоимость часа работы тракториста, тг/ч", f(wage_h, 0), f"зарплата {f(P['wage_month'], 0)} тг/мес (с/х, II кв. 2026) [@stat_wage] × {f(P['k_soc'], 2)} / {f(P['h_month'], 0)} ч"),
