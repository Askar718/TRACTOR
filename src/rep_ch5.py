        ("Стоимость замены батареи, $/(кВт·ч)", f(P['bat_usd_kWh'], 0), "2,5 × средняя цена пакета LFP в 2025 г. (81 $/(кВт·ч)) [@bnef2025]"),
        ("Ресурс батареи: циклов; лет", f"{f(P['bat_cycles'], 0)}; {f(P['bat_cal_y'], 0)}", "LiFePO_{4} [@preger2020]"),
        ("Коэффициент эмиссии сети, кг CO_{2}/(кВт·ч)", f(P['EF_grid'], 3), "Казахстан, IEA-2025 [@abb2025]"),
