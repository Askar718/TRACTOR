"""Раздел 5. Результаты сравнительной оценки."""
import numpy as np

from models import CRITERIA
from repdata import FIG, f, pc

CODES = [c[0] for c in CRITERIA]


def short(impl, a, v):
    return f"{'К' if impl == 'культиватор' else 'Ф'} {f(a, 2)}×{f(v, 1)}"


def verdict(p):
    if p >= 0.9:
        return "устойчивое ЭТ"
    if p >= 0.5:
        return "условное ЭТ"
    if p > 0.1:
        return "условное Д"
    return "устойчивое Д"


